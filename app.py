
import streamlit as st
import json
from io import BytesIO
from html import escape

from google import genai

from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    PageBreak
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors


# =========================
# PAGE SETTINGS
# =========================

st.set_page_config(
    page_title="AI Learning Chatbot",
    page_icon="🤖",
    layout="centered"
)

st.title("🤖 AI Learning Chatbot")
st.caption("AI Tutor | Quiz Generator | Automatic Result Checker")


# =========================
# GEMINI API CONNECTION
# =========================

try:
    api_key = st.secrets["GEMINI_API_KEY"]
    client = genai.Client(api_key=api_key)

except Exception:
    st.error(
        "Gemini API key missing. "
        "Please check Streamlit Secrets."
    )
    st.stop()


MODEL = "gemini-3.5-flash-lite"


# =========================
# ASK AI FUNCTION
# =========================

def ask_ai(question):

    prompt = f"""
You are a helpful AI tutor.

Understand the user's language and reply in the same language.

- English question: answer in English.
- Roman Urdu question: answer in Roman Urdu.
- Urdu script question: answer in Urdu script.

Explain in simple words and give examples when useful.

User question: {question}
"""

    response = client.models.generate_content(
        model=MODEL,
        contents=prompt
    )

    return response.text


# =========================
# QUIZ GENERATOR FUNCTION
# =========================

def create_quiz(topic, number, difficulty, language):

    prompt = f"""
Create a Machine Learning and AI learning quiz.

Topic: {topic}
Number of questions: {number}
Difficulty: {difficulty}
Language: {language}

Return ONLY valid JSON in this exact structure:

{{
  "title": "Quiz title",
  "questions": [
    {{
      "question": "Question text",
      "options": {{
        "A": "Option A",
        "B": "Option B",
        "C": "Option C",
        "D": "Option D"
      }},
      "answer": "A",
      "explanation": "Short explanation"
    }}
  ]
}}

Rules:
- Include exactly {number} questions.
- Each question must have four options A, B, C, D.
- Exactly one correct answer per question.
- The answer must contain only A, B, C, or D.
- Keep all quiz text in the requested language.
- Do not include Markdown fences or text outside JSON.
"""

    response = client.models.generate_content(
        model=MODEL,
        contents=prompt,
        config={
            "response_mime_type": "application/json"
        }
    )

    return json.loads(response.text)


# =========================
# PDF GENERATOR FUNCTION
# =========================

def make_quiz_pdf(quiz):

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "QuizTitle",
        parent=styles["Title"],
        fontSize=20,
        textColor=colors.darkblue,
        spaceAfter=20
    )

    question_style = ParagraphStyle(
        "QuestionStyle",
        parent=styles["Heading3"],
        fontSize=12,
        leading=16,
        spaceBefore=10,
        spaceAfter=8
    )

    normal_style = ParagraphStyle(
        "NormalStyle",
        parent=styles["Normal"],
        fontSize=10,
        leading=15,
        spaceAfter=5
    )

    answer_style = ParagraphStyle(
        "AnswerStyle",
        parent=styles["Normal"],
        fontSize=10,
        textColor=colors.darkgreen,
        leading=15,
        spaceAfter=5
    )

    content = []

    # Quiz title
    content.append(
        Paragraph(
            escape(str(quiz.get("title", "AI Learning Quiz"))),
            title_style
        )
    )

    content.append(
        Paragraph(
            "Generated by AI Learning Chatbot",
            normal_style
        )
    )

    content.append(Spacer(1, 15))

    # Questions and options
    for i, question in enumerate(quiz["questions"]):

        content.append(
            Paragraph(
                f"Q{i+1}. {escape(str(question['question']))}",
                question_style
            )
        )

        options = question["options"]

        for key in ["A", "B", "C", "D"]:

            if key in options:

                option_text = (
                    f"{key}) {escape(str(options[key]))}"
                )

                content.append(
                    Paragraph(option_text, normal_style)
                )

        content.append(Spacer(1, 8))

    # Answer key
    content.append(PageBreak())

    content.append(
        Paragraph("Answer Key and Explanations", title_style)
    )

    for i, question in enumerate(quiz["questions"]):

        correct_answer = escape(
            str(question["answer"])
        )

        explanation = escape(
            str(question["explanation"])
        )

        content.append(
            Paragraph(
                f"Q{i+1}. Correct Answer: {correct_answer}",
                answer_style
            )
        )

        content.append(
            Paragraph(
                f"Explanation: {explanation}",
                normal_style
            )
        )

        content.append(Spacer(1, 10))

    # Create PDF
    doc.build(content)

    buffer.seek(0)

    return buffer.getvalue()


# =========================
# APPLICATION TABS
# =========================

chat_tab, quiz_tab = st.tabs(
    ["💬 Ask AI", "📝 Generate Quiz"]
)


# =========================
# ASK AI SECTION
# =========================

with chat_tab:

    st.subheader("Ask your AI Tutor")

    if "messages" not in st.session_state:
        st.session_state.messages = []

    # Display previous messages
    for message in st.session_state.messages:

        with st.chat_message(message["role"]):
            st.markdown(message["content"])

    # User question
    user_question = st.chat_input(
        "Apna question likhein..."
    )

    if user_question:

        st.session_state.messages.append({
            "role": "user",
            "content": user_question
        })

        with st.chat_message("user"):
            st.markdown(user_question)

        with st.chat_message("assistant"):

            with st.spinner("AI jawab tayyar kar raha hai..."):

                try:

                    answer = ask_ai(user_question)

                    st.markdown(answer)

                    st.session_state.messages.append({
                        "role": "assistant",
                        "content": answer
                    })

                except Exception as e:

                    st.error(f"AI error: {e}")

    # Clear chat
    if st.button("Clear Chat"):

        st.session_state.messages = []

        st.rerun()


# =========================
# QUIZ GENERATOR SECTION
# =========================

with quiz_tab:

    st.subheader("Create Your Quiz")

    # Quiz form
    with st.form("quiz_form"):

        topic = st.text_input(
            "Quiz Topic",
            placeholder="e.g. Machine Learning"
        )

        number = st.number_input(
            "Number of Questions",
            min_value=1,
            max_value=20,
            value=5
        )

        difficulty = st.selectbox(
            "Difficulty",
            ["Easy", "Medium", "Hard"]
        )

        language = st.selectbox(
            "Language",
            ["English", "Roman Urdu", "Urdu"]
        )

        generate = st.form_submit_button(
            "Generate Quiz"
        )

    # Generate quiz
    if generate:

        if not topic.strip():

            st.warning("Please enter a quiz topic.")

        else:

            try:

                with st.spinner("Quiz generate ho raha hai..."):

                    new_quiz = create_quiz(
                        topic,
                        int(number),
                        difficulty,
                        language
                    )

                    st.session_state.quiz = new_quiz

                    st.session_state.quiz_submitted = False

                    st.session_state.quiz_answers = {}

            except Exception as e:

                st.error(f"Quiz generation error: {e}")


    # Display quiz
    if "quiz" in st.session_state:

        quiz = st.session_state.quiz

        st.divider()

        st.subheader(
            quiz.get("title", "Your Quiz")
        )

        # PDF download button
        try:

            pdf_file = make_quiz_pdf(quiz)

            st.download_button(
                label="📥 Download Quiz PDF",
                data=pdf_file,
                file_name="AI_Learning_Quiz.pdf",
                mime="application/pdf"
            )

        except Exception as e:

            st.error(f"PDF creation error: {e}")


        # Student answers
        if not st.session_state.get(
            "quiz_submitted", False
        ):

            with st.form("answer_form"):

                for i, question in enumerate(
                    quiz["questions"]
                ):

                    st.markdown(
                        f"**Q{i+1}. {question['question']}**"
                    )

                    options = question["options"]

                    choice = st.radio(
                        "Select your answer:",
                        options=list(options.keys()),
                        format_func=lambda key: (
                            f"{key}) {options[key]}"
                        ),
                        key=f"answer_{i}",
                        index=None
                    )

                    st.session_state.quiz_answers[i] = choice

                    st.divider()

                submitted = st.form_submit_button(
                    "Submit Answers"
                )

            if submitted:

                st.session_state.quiz_submitted = True

                st.rerun()


        # Quiz result
        else:

            score = 0

            questions = quiz["questions"]

            st.subheader("📊 Your Quiz Result")

            for i, question in enumerate(questions):

                correct = question["answer"].upper()

                student = st.session_state.quiz_answers.get(i)

                st.markdown(
                    f"**Q{i+1}. {question['question']}**"
                )

                if student == correct:

                    score += 1

                    st.success(
                        f"Correct! Your answer: {student}"
                    )

                else:

                    st.error(
                        f"Incorrect. Your answer: "
                        f"{student or 'Not answered'}"
                    )

                    st.info(
                        f"Correct answer: {correct}"
                    )

                st.write(
                    f"Explanation: {question['explanation']}"
                )

                st.divider()

            total = len(questions)

            percentage = (score / total) * 100

            st.metric(
                "Obtained Marks",
                f"{score} / {total}"
            )

            st.metric(
                "Percentage",
                f"{percentage:.1f}%"
            )

            # Generate another quiz
            if st.button("Generate Another Quiz"):

                del st.session_state.quiz

                st.session_state.quiz_submitted = False

                st.session_state.quiz_answers = {}

                st.rerun()
